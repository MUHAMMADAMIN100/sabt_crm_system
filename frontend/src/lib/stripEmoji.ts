/**
 * Убирает лидирующие эмодзи + пробелы из строки. Используется чтобы
 * старые названия задач, сохранённые с префиксом 📋/📅/📞 (генерировались
 * автоматически из лидов), отображались чисто — без стикеров.
 *
 * Бэк больше не вставляет эмодзи в новые названия (см. clients.service.ts),
 * но в БД уже накопились старые. Стрипаем при рендере.
 */
export function stripLeadingEmoji(s: string | null | undefined): string {
  if (!s) return ''
  // Регексп ловит любые символы из основных Unicode-блоков эмодзи и пиктограмм,
  // плюс variation selectors / ZWJ-связки, повторённые произвольное число раз
  // в начале строки, и потом ведущие пробелы.
  return s.replace(
    /^(?:[⌀-➿\u{1F300}-\u{1FAFF}\u{2600}-\u{26FF}️‍]+\s*)+/u,
    '',
  ).trimStart()
}
